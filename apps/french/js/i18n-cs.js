const N = '(\\d[\\d\\u00a0\\u202f ,.]*K?)';
const num = s => Number(s.replace(/[^\d]/g, ''));
const pick = (n, forms) => (n === 1 ? forms[0] : n >= 2 && n <= 4 ? forms[1] : forms[2]);
const t = s => CS[s] ?? s;
const lookup = s => CS[s] ?? CS_PATTERNS.reduce((out, [re, fn]) => out ?? (re.test(s) ? fn(...s.match(re).slice(1)) : undefined), undefined);
const lower = s => t(s).toLowerCase();
const LANGS = new Set(['French', 'German', 'Czech', 'English']);

// "{n}" is a number, "{x}" any text. Each entry turns the English text into Czech.
const P = (template, fn) => [
  new RegExp(`^${template.replace(/[.*+?^$()|[\]\\]/g, '\\$&').replace(/\{n\}/g, N).replace(/\{x\}/g, '(.+?)')}$`),
  fn,
];

